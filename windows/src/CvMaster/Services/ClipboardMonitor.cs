/**
 * 事件驱动剪贴板监听：WM_CLIPBOARDUPDATE 触发，STA 工作线程读取并限流。
 * 只保存受控格式；敏感标记、排除进程、暂停状态在读取前判断。
 * @author helele
 * @since 2026-10-19
 */
using System.Collections.Concurrent;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using System.Windows.Interop;
using System.Windows.Media.Imaging;
using CvMaster.Core;
using CvMaster.Interop;

namespace CvMaster.Services;

public sealed class ClipboardMonitor : IDisposable
{
    private readonly Func<bool> _shouldRecord;
    private readonly Func<bool> _skipSensitive;
    private readonly Func<IReadOnlyCollection<string>> _excludedProcesses;
    private readonly Func<ForegroundInfo?> _foreground;
    private readonly Action<ClipCapture> _accept;
    private readonly Action<LibraryErrorCode> _report;
    private readonly HwndSource _source;
    private readonly BlockingCollection<Action> _queue = new(new ConcurrentQueue<Action>());
    private readonly Thread _worker;
    private readonly object _sequenceGate = new();
    private readonly uint _htmlFormat = NativeMethods.RegisterClipboardFormatW("HTML Format");
    private readonly uint _rtfFormat = NativeMethods.RegisterClipboardFormatW("Rich Text Format");
    private readonly uint _pngFormat = NativeMethods.RegisterClipboardFormatW("PNG");
    private readonly uint _urlFormat = NativeMethods.RegisterClipboardFormatW("UniformResourceLocatorW");
    private readonly uint _excludeFormat = NativeMethods.RegisterClipboardFormatW("ExcludeClipboardContentFromMonitorProcessing");
    private readonly uint _viewerIgnoreFormat = NativeMethods.RegisterClipboardFormatW("Clipboard Viewer Ignore");
    private readonly uint _canIncludeFormat = NativeMethods.RegisterClipboardFormatW("CanIncludeInClipboardHistory");
    private readonly uint _concealedFormat = NativeMethods.RegisterClipboardFormatW("org.nspasteboard.ConcealedType");
    private readonly uint _transientFormat = NativeMethods.RegisterClipboardFormatW("org.nspasteboard.TransientType");
    private readonly uint _autoGeneratedFormat = NativeMethods.RegisterClipboardFormatW("org.nspasteboard.AutoGeneratedType");
    private uint _baselineSequence;
    private uint _suppressSequence;
    private uint _lastAcceptedSequence;
    private int _busy;
    private int _selfWrite;
    private int _pendingRead;
    private ForegroundInfo? _pendingSource;
    private bool _pendingSkipSensitive;
    private bool _started;
    private bool _disposed;

    public ClipboardMonitor(
        Func<bool> shouldRecord,
        Func<bool> skipSensitive,
        Func<IReadOnlyCollection<string>> excludedProcesses,
        Func<ForegroundInfo?> foreground,
        Action<ClipCapture> accept,
        Action<LibraryErrorCode> report)
    {
        _shouldRecord = shouldRecord;
        _skipSensitive = skipSensitive;
        _excludedProcesses = excludedProcesses;
        _foreground = foreground;
        _accept = accept;
        _report = report;

        var parameters = new HwndSourceParameters("cvMaster.ClipboardMonitor")
        {
            Width = 0,
            Height = 0,
            WindowStyle = 0,
            ParentWindow = NativeMethods.HWND_MESSAGE
        };
        _source = new HwndSource(parameters);
        _source.AddHook(WndProc);

        _worker = new Thread(WorkerLoop)
        {
            IsBackground = true,
            Name = "cvMaster clipboard"
        };
        _worker.SetApartmentState(ApartmentState.STA);
        _worker.Start();
    }

    public void Start()
    {
        if (_started || _disposed)
        {
            return;
        }

        _started = NativeMethods.AddClipboardFormatListener(_source.Handle);
        if (!_started)
        {
            AppLog.Error("clipboard-listener");
        }

        ResetBaseline();
    }

    /// <summary>应用主动写入或清空后抑制自身触发，并跳过当前序列。</summary>
    public void SuppressNextSequence(uint sequence)
    {
        lock (_sequenceGate)
        {
            _suppressSequence = sequence;
            _baselineSequence = sequence;
        }
    }

    public void BeginSelfWrite() => Interlocked.Exchange(ref _selfWrite, 1);

    public void EndSelfWrite(uint sequence)
    {
        SuppressNextSequence(sequence);
        Interlocked.Exchange(ref _selfWrite, 0);
    }

    /// <summary>启用、暂停或清空后重置基线，不回溯当前剪贴板内容。</summary>
    public void ResetBaseline()
    {
        lock (_sequenceGate)
        {
            _baselineSequence = NativeMethods.GetClipboardSequenceNumber();
            _suppressSequence = 0;
        }
    }

    private void OnClipboardUpdate()
    {
        var sequence = NativeMethods.GetClipboardSequenceNumber();
        lock (_sequenceGate)
        {
            if (sequence == _suppressSequence)
            {
                _suppressSequence = 0;
                return;
            }

            if (sequence == _baselineSequence)
            {
                return;
            }

            _baselineSequence = sequence;
        }

        if (Volatile.Read(ref _selfWrite) == 1)
        {
            return;
        }

        try
        {
            if (!_shouldRecord())
            {
                return;
            }
        }
        catch (Exception exception)
        {
            AppLog.Error("clipboard-record-state", exception);
            return;
        }

        var source = _foreground();
        if (source is null || source.ProcessId == Environment.ProcessId)
        {
            return;
        }

        var excluded = _excludedProcesses();
        if (excluded.Any(item =>
                ProcessCatalog.Normalize(item).Equals(source.ProcessName, StringComparison.OrdinalIgnoreCase)))
        {
            return;
        }

        var skipSensitive = _skipSensitive();
        lock (_sequenceGate)
        {
            _pendingSource = source;
            _pendingSkipSensitive = skipSensitive;
        }

        Interlocked.Exchange(ref _pendingRead, 1);
        StartReadWorker();
    }

    private void StartReadWorker()
    {
        if (_disposed || Volatile.Read(ref _pendingRead) == 0)
        {
            return;
        }

        if (Interlocked.CompareExchange(ref _busy, 1, 0) != 0)
        {
            return;
        }

        try
        {
            _queue.Add(ReadLatestLoop);
        }
        catch (Exception exception) when (exception is InvalidOperationException or ObjectDisposedException)
        {
            // 队列已关闭；释放占用，不阻塞退出流程。
            Interlocked.Exchange(ref _busy, 0);
        }
    }

    /// <summary>
    /// 合并同一轮复制产生的连续 WM_CLIPBOARDUPDATE（先清空再写入）。
    /// 延迟读取当前稳定快照；读取期间再次变化则重试，避免丢弃最终内容。
    /// </summary>
    private void ReadLatestLoop()
    {
        try
        {
            for (var attempt = 0; attempt < 3; attempt++)
            {
                if (Interlocked.Exchange(ref _pendingRead, 0) == 0)
                {
                    break;
                }

                Thread.Sleep(attempt == 0 ? 60 : 40);
                if (!_shouldRecord())
                {
                    break;
                }

                ForegroundInfo? source;
                bool skipSensitive;
                lock (_sequenceGate)
                {
                    source = _pendingSource;
                    skipSensitive = _pendingSkipSensitive;
                }

                if (source is null)
                {
                    break;
                }

                var sequence = NativeMethods.GetClipboardSequenceNumber();
                var capture = ReadClipboard(source, skipSensitive);
                if (capture is null)
                {
                    if (Volatile.Read(ref _pendingRead) == 0)
                    {
                        break;
                    }

                    continue;
                }

                if (NativeMethods.GetClipboardSequenceNumber() != sequence)
                {
                    // 通知可能已被合并或过滤；主动标记，保证继续读取最终快照。
                    Interlocked.Exchange(ref _pendingRead, 1);
                    continue;
                }

                if (sequence != _lastAcceptedSequence)
                {
                    _lastAcceptedSequence = sequence;
                    _accept(capture);
                }

                if (Volatile.Read(ref _pendingRead) == 0)
                {
                    break;
                }
            }
        }
        catch (LibraryException exception)
        {
            _report(exception.Code);
        }
        catch (Exception exception)
        {
            AppLog.Error("clipboard-capture", exception);
            _report(LibraryErrorCode.Storage);
        }
        finally
        {
            Interlocked.Exchange(ref _busy, 0);
            StartReadWorker();
        }
    }

    private ClipCapture? ReadClipboard(ForegroundInfo source, bool skipSensitive)
    {
        var opened = false;
        for (var attempt = 0; attempt < 6; attempt++)
        {
            if (NativeMethods.OpenClipboard(IntPtr.Zero))
            {
                opened = true;
                break;
            }

            Thread.Sleep(20);
        }

        if (!opened)
        {
            return null;
        }

        try
        {
            var formats = new HashSet<uint>();
            var format = 0u;
            while ((format = NativeMethods.EnumClipboardFormats(format)) != 0)
            {
                formats.Add(format);
            }

            // 明确要求“不要被剪贴板监视器读取”的标记始终尊重。
            if (formats.Contains(_excludeFormat) || formats.Contains(_viewerIgnoreFormat))
            {
                return null;
            }

            if (skipSensitive)
            {
                if (formats.Contains(_concealedFormat) ||
                    formats.Contains(_transientFormat) ||
                    formats.Contains(_autoGeneratedFormat))
                {
                    return null;
                }

                if (formats.Contains(_canIncludeFormat) && ReadDword(_canIncludeFormat) == 0)
                {
                    return null;
                }
            }

            var files = formats.Contains(NativeMethods.CF_HDROP) ? ReadFileDrop() : [];
            var imagePng = formats.Contains(_pngFormat) ? ReadPng(_pngFormat) : null;
            if (imagePng is null)
            {
                imagePng = formats.Contains(NativeMethods.CF_DIBV5)
                    ? ReadDibAsPng(NativeMethods.CF_DIBV5)
                    : formats.Contains(NativeMethods.CF_DIB)
                        ? ReadDibAsPng(NativeMethods.CF_DIB)
                        : null;
            }

            string? text = null;
            if (formats.Contains(NativeMethods.CF_UNICODETEXT))
            {
                text = ReadUnicodeString(NativeMethods.CF_UNICODETEXT);
            }
            else if (formats.Contains(NativeMethods.CF_TEXT))
            {
                text = ReadAnsiString(NativeMethods.CF_TEXT);
            }

            var urlText = formats.Contains(_urlFormat) ? ReadUnicodeString(_urlFormat) : null;
            if (string.IsNullOrWhiteSpace(text) && !string.IsNullOrWhiteSpace(urlText))
            {
                text = urlText;
            }

            var html = formats.Contains(_htmlFormat)
                ? ReadBytes(_htmlFormat, StorageLimits.MaximumRepresentationBytes)
                : null;
            var rtf = formats.Contains(_rtfFormat)
                ? ReadBytes(_rtfFormat, StorageLimits.MaximumRepresentationBytes)
                : null;

            if (files.Length == 0 && imagePng is null && string.IsNullOrWhiteSpace(text) &&
                html is null && rtf is null)
            {
                return null;
            }

            var fileNames = files.Select(Path.GetFileName).Where(name => !string.IsNullOrEmpty(name)).OfType<string>().ToArray();
            var searchText = files.Length > 0
                ? string.Join("\n", fileNames)
                : text ?? TextExtraction.FromRtf(rtf ?? []) ?? TextExtraction.FromHtml(html ?? []) ?? string.Empty;
            searchText = TextExtraction.Truncate(searchText.Trim(), StorageLimits.SearchableCharacters);

            var hasUrl = IsHttpUrl(text) || IsHttpUrl(urlText);
            var allFilesAreImages = files.Length > 0 && files.All(IsImagePath);
            var kind = files.Length > 0
                ? (allFilesAreImages ? ClipKind.Image : ClipKind.File)
                : imagePng is not null
                    ? ClipKind.Image
                    : hasUrl
                        ? ClipKind.Link
                        : ClipKind.Text;

            var title = files.Length > 0
                ? fileNames.Length == 1
                    ? fileNames[0]
                    : $"{fileNames.FirstOrDefault() ?? "文件"} 等 {files.Length} 个文件"
                : kind == ClipKind.Image
                    ? "图片"
                    : TextExtraction.FirstLine(searchText, StorageLimits.MaximumTitleCharacters, "富文本内容");
            var excerpt = TextExtraction.Truncate(searchText, StorageLimits.MaximumExcerptCharacters);

            var representations = new List<ClipRepresentation>();
            long totalBytes = 0;
            void AddRepresentation(string type, byte[] data)
            {
                if (data.Length == 0)
                {
                    return;
                }

                if (data.Length > StorageLimits.MaximumRepresentationBytes)
                {
                    throw new LibraryException(LibraryErrorCode.Unsupported);
                }

                totalBytes += data.Length;
                if (totalBytes > StorageLimits.MaximumCaptureBytes ||
                    representations.Count >= StorageLimits.MaximumRepresentations)
                {
                    throw new LibraryException(LibraryErrorCode.Unsupported);
                }

                representations.Add(new ClipRepresentation(0, type, data));
            }

            if (files.Length > 0)
            {
                AddRepresentation("windows/file-list", HistoryStore.EncodeFileList(files));
            }

            if (!string.IsNullOrEmpty(text))
            {
                AddRepresentation("text/plain", Encoding.UTF8.GetBytes(text));
            }

            if (html is not null)
            {
                AddRepresentation("text/html", html);
            }

            if (rtf is not null)
            {
                AddRepresentation("text/rtf", rtf);
            }

            if (imagePng is not null)
            {
                AddRepresentation("image/png", imagePng);
            }

            if (representations.Count == 0)
            {
                return null;
            }

            return new ClipCapture
            {
                Kind = kind,
                Title = title,
                Excerpt = excerpt,
                SearchText = searchText,
                Source = ProcessCatalog.DisplayName(source.ProcessName),
                SourceProcess = source.ProcessName,
                Representations = representations
            };
        }
        finally
        {
            NativeMethods.CloseClipboard();
        }
    }

    private static string[] ReadFileDrop()
    {
        var handle = NativeMethods.GetClipboardData(NativeMethods.CF_HDROP);
        if (handle == IntPtr.Zero)
        {
            return [];
        }

        var count = NativeMethods.DragQueryFileW(handle, uint.MaxValue, null, 0);
        if (count == 0)
        {
            return [];
        }

        if (count > StorageLimits.MaximumFileReferences)
        {
            throw new LibraryException(LibraryErrorCode.Unsupported);
        }

        var files = new List<string>((int)count);
        var buffer = new StringBuilder(32768);
        for (var index = 0u; index < count; index++)
        {
            buffer.Clear();
            var length = NativeMethods.DragQueryFileW(handle, index, buffer, buffer.Capacity);
            if (length > 0 && length < buffer.Capacity)
            {
                files.Add(buffer.ToString());
            }
        }

        return files.ToArray();
    }

    private byte[]? ReadPng(uint format)
    {
        var bytes = ReadBytes(format, StorageLimits.MaximumRepresentationBytes);
        if (bytes is null || bytes.Length < 24)
        {
            return null;
        }

        ReadOnlySpan<byte> signature = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
        if (!bytes.AsSpan(0, 8).SequenceEqual(signature))
        {
            return null;
        }

        var width = ReadBigEndianInt32(bytes, 16);
        var height = ReadBigEndianInt32(bytes, 20);
        if (!IsReasonableImage(width, height))
        {
            return null;
        }

        return bytes;
    }

    private byte[]? ReadDibAsPng(uint format)
    {
        var dib = ReadBytes(format, StorageLimits.MaximumRepresentationBytes);
        if (dib is null || dib.Length < 40)
        {
            return null;
        }

        var headerSize = BitConverter.ToInt32(dib, 0);
        if (headerSize is not (40 or 52 or 56 or 108 or 124) || dib.Length < headerSize)
        {
            return null;
        }

        var width = BitConverter.ToInt32(dib, 4);
        var height = Math.Abs(BitConverter.ToInt32(dib, 8));
        if (!IsReasonableImage(width, height))
        {
            return null;
        }

        var bitsPerPixel = BitConverter.ToUInt16(dib, 14);
        var compression = BitConverter.ToInt32(dib, 16);
        var paletteBytes = 0;
        if (compression == 0 && bitsPerPixel <= 8)
        {
            paletteBytes = (1 << bitsPerPixel) * 4;
        }
        else if (compression == 3 && headerSize == 40)
        {
            paletteBytes = 12;
        }
        else if (compression == 6 && headerSize == 40)
        {
            paletteBytes = 16;
        }

        var offset = 14 + headerSize + paletteBytes;
        var bmp = new byte[14 + dib.Length];
        bmp[0] = (byte)'B';
        bmp[1] = (byte)'M';
        BitConverter.TryWriteBytes(bmp.AsSpan(2, 4), bmp.Length);
        BitConverter.TryWriteBytes(bmp.AsSpan(10, 4), offset);
        dib.CopyTo(bmp, 14);

        try
        {
            using var input = new MemoryStream(bmp, writable: false);
            var frame = BitmapFrame.Create(input, BitmapCreateOptions.IgnoreColorProfile, BitmapCacheOption.OnLoad);
            if (!IsReasonableImage(frame.PixelWidth, frame.PixelHeight))
            {
                return null;
            }

            frame.Freeze();
            using var output = new MemoryStream();
            var encoder = new PngBitmapEncoder();
            encoder.Frames.Add(frame);
            encoder.Save(output);
            if (output.Length > StorageLimits.MaximumRepresentationBytes)
            {
                throw new LibraryException(LibraryErrorCode.Unsupported);
            }

            return output.ToArray();
        }
        catch (LibraryException)
        {
            throw;
        }
        catch (Exception exception) when (exception is IOException or NotSupportedException or ArgumentException)
        {
            return null;
        }
    }

    private byte[]? ReadBytes(uint format, int maximumBytes)
    {
        var handle = NativeMethods.GetClipboardData(format);
        if (handle == IntPtr.Zero)
        {
            return null;
        }

        var size = NativeMethods.GlobalSize(handle);
        if (size == UIntPtr.Zero)
        {
            return null;
        }

        var length = size.ToUInt64();
        if (length > int.MaxValue || length > (ulong)maximumBytes)
        {
            throw new LibraryException(LibraryErrorCode.Unsupported);
        }

        var pointer = NativeMethods.GlobalLock(handle);
        if (pointer == IntPtr.Zero)
        {
            return null;
        }

        try
        {
            var bytes = new byte[(int)length];
            Marshal.Copy(pointer, bytes, 0, bytes.Length);
            return bytes;
        }
        finally
        {
            NativeMethods.GlobalUnlock(handle);
        }
    }

    private string? ReadUnicodeString(uint format)
    {
        var handle = NativeMethods.GetClipboardData(format);
        if (handle == IntPtr.Zero)
        {
            return null;
        }

        var size = NativeMethods.GlobalSize(handle);
        if (size == UIntPtr.Zero)
        {
            return null;
        }

        var length = size.ToUInt64();
        if (length > (ulong)StorageLimits.MaximumRepresentationBytes * 2)
        {
            throw new LibraryException(LibraryErrorCode.Unsupported);
        }

        var pointer = NativeMethods.GlobalLock(handle);
        if (pointer == IntPtr.Zero)
        {
            return null;
        }

        try
        {
            var value = Marshal.PtrToStringUni(pointer, (int)(length / 2));
            return value?.TrimEnd('\0');
        }
        finally
        {
            NativeMethods.GlobalUnlock(handle);
        }
    }

    private string? ReadAnsiString(uint format)
    {
        var bytes = ReadBytes(format, StorageLimits.MaximumRepresentationBytes);
        return bytes is null ? null : Encoding.Latin1.GetString(bytes).TrimEnd('\0');
    }

    private static int ReadDword(uint format)
    {
        var handle = NativeMethods.GetClipboardData(format);
        if (handle == IntPtr.Zero)
        {
            return -1;
        }

        var size = NativeMethods.GlobalSize(handle);
        if (size.ToUInt64() < 4)
        {
            return -1;
        }

        var pointer = NativeMethods.GlobalLock(handle);
        if (pointer == IntPtr.Zero)
        {
            return -1;
        }

        try
        {
            return Marshal.ReadInt32(pointer);
        }
        finally
        {
            NativeMethods.GlobalUnlock(handle);
        }
    }

    private static int ReadBigEndianInt32(byte[] value, int offset) =>
        (value[offset] << 24) | (value[offset + 1] << 16) | (value[offset + 2] << 8) | value[offset + 3];

    private static bool IsReasonableImage(int width, int height) =>
        width > 0 && height > 0 && (long)width * height <= StorageLimits.MaximumImagePixels;

    private static bool IsHttpUrl(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return false;
        }

        var trimmed = value.Trim();
        return trimmed.Length <= 8192 &&
               Uri.TryCreate(trimmed, UriKind.Absolute, out var uri) &&
               (uri.Scheme == Uri.UriSchemeHttp || uri.Scheme == Uri.UriSchemeHttps) &&
               !string.IsNullOrEmpty(uri.Host);
    }

    private static bool IsImagePath(string path) => Path.GetExtension(path).ToLowerInvariant() is
        ".png" or ".jpg" or ".jpeg" or ".gif" or ".bmp" or ".webp" or ".tif" or ".tiff" or ".heic" or ".heif" or ".ico";

    private IntPtr WndProc(IntPtr hwnd, int message, IntPtr wParam, IntPtr lParam, ref bool handled)
    {
        if (message == NativeMethods.WM_CLIPBOARDUPDATE)
        {
            handled = true;
            try
            {
                OnClipboardUpdate();
            }
            catch (Exception exception)
            {
                AppLog.Error("clipboard-update", exception);
            }
        }

        return IntPtr.Zero;
    }

    private void WorkerLoop()
    {
        foreach (var work in _queue.GetConsumingEnumerable())
        {
            try
            {
                work();
            }
            catch (Exception exception)
            {
                AppLog.Error("clipboard-worker", exception);
            }
        }
    }

    public void Dispose()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;
        if (_started)
        {
            NativeMethods.RemoveClipboardFormatListener(_source.Handle);
            _started = false;
        }

        _source.RemoveHook(WndProc);
        _source.Dispose();
        _queue.CompleteAdding();
        if (Thread.CurrentThread != _worker)
        {
            _worker.Join(1000);
        }

        // 不释放 BlockingCollection：工作线程可能仍在完成最后一张快照；
        // 应用即将退出，交由进程回收，避免关闭竞态抛 ObjectDisposedException。
    }
}
