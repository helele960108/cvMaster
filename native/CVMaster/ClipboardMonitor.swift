/**
 * 通用剪贴板轻量监测：500 ms 轮询、休眠暂停、明确同意后采集及敏感标记排除。
 * @author helele
 * @since 2026-10-19
 */
import AppKit
import OSLog

@MainActor
final class ClipboardMonitor {
    /// 反向弱引用避免状态容器与轮询服务互相持有。
    private weak var library: ClipboardLibrary?
    /// 低频计时器不持有大体积内容，sleep 期间自动失活。
    private var timer: Timer?
    /// 捕获启动前剪贴板基线，首次开启不回溯采集已有内容。
    private var lastChange = NSPasteboard.general.changeCount
    private var sleeping = false
    private var observers: [NSObjectProtocol] = []
    private let logger = Logger(subsystem: "local.helele.cvmaster", category: "clipboard")
    /// 尽量只保存一种图片编码，避免同一图像 PNG/TIFF 重复持有。
    private let imageTypes = ClipboardFormats.rasterImages.map { NSPasteboard.PasteboardType($0) }
    private let sensitiveTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(library: ClipboardLibrary) { self.library = library }

    /// 整个进程仅启动一个轮询器，退出时显式释放计时器和观察者。
    func start() {
        guard timer == nil else { return }
        resetBaseline()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        let center = NSWorkspace.shared.notificationCenter
        observers.append(center.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.sleeping = true }
        })
        observers.append(center.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.sleeping = false; self?.resetBaseline() }
        })
    }

    func stop() {
        timer?.invalidate(); timer = nil
        for observer in observers { NSWorkspace.shared.notificationCenter.removeObserver(observer) }
        observers.removeAll()
    }

    /// 应用主动复制、暂停或授权变更后更新基线，避免自采集和追溯暂停期间内容。
    func resetBaseline() { lastChange = NSPasteboard.general.changeCount }

    private func poll() {
        guard !sleeping, let library else { return }
        let pasteboard = NSPasteboard.general
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard library.recordingEnabled, !library.paused else { return }
        guard !library.captureBusy else { library.skippedChange(); return }
        let source = NSWorkspace.shared.frontmostApplication
        let exclusions = library.excludedApplicationIDSet
        if let bundle = source?.bundleIdentifier, exclusions.contains(bundle.lowercased()) { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard sensitiveTypes.isDisjoint(with: types) else { return }
        do {
            if let capture = try snapshot(pasteboard, source: source?.localizedName ?? "未知应用", bundleID: source?.bundleIdentifier ?? ""), pasteboard.changeCount == change {
                library.accept(capture)
            }
        } catch {
            logger.notice("Clipboard capture skipped: unsupported or over size budget")
            library.notify(LibraryError.unsupported.localizedDescription)
        }
    }

    /// AppKit 数据读取发生在主线程；仅白名单、有界数量和大小，不解析或解码原图。
    /// 延迟提供数据在读取前无法预知大小，读取后立即限额；系统调用仍可能短暂阻塞。
    private func snapshot(_ pasteboard: NSPasteboard, source: String, bundleID: String) throws -> ClipCapture? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        guard items.count <= StorageLimits.maximumRepresentations else { throw LibraryError.unsupported }
        var representations: [ClipRepresentation] = []
        var size = 0
        var text = ""
        var files: [String] = []
        var hasImage = false
        var hasURL = false
        for (index, item) in items.enumerated() {
            // 同一 item 的纯文本与 URL 只选一种，不重复索引同内容的多种表示。
            var itemText = ""
            guard sensitiveTypes.isDisjoint(with: Set(item.types.map(\.rawValue))) else { return nil }
            // 声明格式不代表一定能取到数据。逐个回退，只有成功保存后才标记图片。
            // 文件 URL 与图片像素可以同时存在：保留像素以便源文件消失后仍可预览，
            // 但再次复制仍保留文件表示；用户可见类型按文件内容识别，不自动备份引用文件。
            for type in imageTypes where item.types.contains(type) {
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                guard data.count <= StorageLimits.maximumRepresentationBytes else { continue }
                guard representations.count < StorageLimits.maximumRepresentations,
                      size + data.count <= StorageLimits.maximumCaptureBytes else { throw LibraryError.unsupported }
                representations.append(ClipRepresentation(item: index, type: type.rawValue, data: data))
                size += data.count
                hasImage = true
                break
            }
            let allowed: [NSPasteboard.PasteboardType]
            if item.types.contains(.fileURL) {
                allowed = [.fileURL]
            } else {
                allowed = [NSPasteboard.PasteboardType.string, .URL, .rtf, .html].filter { item.types.contains($0) }
            }
            for type in allowed {
                guard representations.count < StorageLimits.maximumRepresentations else { throw LibraryError.unsupported }
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                if type == .fileURL {
                    guard let value = String(data: data, encoding: .utf8), let url = URL(string: value), url.isFileURL else { continue }
                }
                size += data.count
                guard data.count <= StorageLimits.maximumRepresentationBytes, size <= StorageLimits.maximumCaptureBytes else { throw LibraryError.unsupported }
                representations.append(ClipRepresentation(item: index, type: type.rawValue, data: data))
                if type == .string { itemText = String(decoding: data.prefix(StorageLimits.searchableCharacters * 4), as: UTF8.self) }
                if type == .URL {
                    hasURL = true
                    if itemText.isEmpty { itemText = String(decoding: data.prefix(StorageLimits.searchableCharacters * 4), as: UTF8.self) }
                }
                if type == .fileURL, let value = String(data: data, encoding: .utf8), let url = URL(string: value), url.isFileURL {
                    files.append(url.lastPathComponent)
                }
            }
            // 按 item 原顺序聚合，并对整条记录应用字符预算，不为每项单独扩容。
            if !itemText.isEmpty, text.count < StorageLimits.searchableCharacters {
                if !text.isEmpty { text += "\n" }
                text += itemText.prefix(StorageLimits.searchableCharacters - text.count)
            }
        }
        guard !representations.isEmpty else { return nil }
        if !hasURL, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
           ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil {
            hasURL = true
        }
        let kind: ClipKind = !files.isEmpty ? (ClipboardFormats.areImageFiles(files) ? .image : .file) : hasImage ? .image : hasURL ? .link : .text
        let searchable = !files.isEmpty ? files.joined(separator: "\n") : String(text.prefix(StorageLimits.searchableCharacters))
        let title: String
        if !files.isEmpty { title = files.count == 1 ? files[0] : "\(files[0]) 等 \(files.count) 个文件" }
        else if hasImage { title = "图片" }
        else { title = String(text.split(whereSeparator: \.isNewline).first?.prefix(120) ?? "富文本内容") }
        return ClipCapture(kind: kind, title: title, excerpt: String(searchable.prefix(240)), searchText: searchable,
                           source: source, sourceBundleID: bundleID, representations: representations)
    }
}
