/**
 * 可注入数据的采集策略：隐私基线、表示限额及 item 完整性，不访问系统剪贴板。
 * @author helele
 * @since 2026-10-20
 */
import Foundation

enum ClipboardCapturePolicy {
    struct Gate {
        private var lastChange: Int?
        private var wasBlocked = false

        mutating func resetBaseline(to change: Int, blocked: Bool) {
            lastChange = change
            wasBlocked = blocked
        }

        mutating func shouldCapture(change: Int, blocked: Bool) -> Bool {
            let previous = lastChange
            let resuming = wasBlocked
            lastChange = change
            wasBlocked = blocked
            return !blocked && !resuming && previous != nil && previous != change
        }
    }

    static func isBlocked(sleeping: Bool, sessionInactive: Bool, onConsole: Bool?,
                          loginComplete: Bool?, secureInput: Bool) -> Bool {
        sleeping || sessionInactive || onConsole != true || loginComplete != true || secureInput
    }

    static let sensitiveTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    private static let fileType = "public.file-url"
    private static let stringType = "public.utf8-plain-text"
    private static let urlType = "public.url"
    private static let textTypes = [stringType, urlType, "public.rtf", "public.html"]
    private static let preferredTypes = ClipboardFormats.rasterImages + [fileType] + textTypes
    private static let typeRanks = Dictionary(uniqueKeysWithValues: preferredTypes.enumerated().map { ($0.element, $0.offset) })

    /// 数据提供者由调用方注入，策略不访问系统剪贴板，便于使用合成内容验证边界。
    static func capture(itemTypes: [[String]], source: String, bundleID: String,
                        readData: (Int, String) throws -> Data?) throws -> ClipCapture? {
        guard !itemTypes.isEmpty else { return nil }
        guard itemTypes.count <= StorageLimits.maximumRepresentations else { throw LibraryError.unsupported }
        guard itemTypes.allSatisfy({ sensitiveTypes.isDisjoint(with: $0) }) else { return nil }
        var representations: [ClipRepresentation] = []
        var attempted = Array(repeating: Set<String>(), count: itemTypes.count)
        var size = 0

        func boundedData(item: Int, type: String) throws -> Data? {
            guard let data = try readData(item, type), !data.isEmpty,
                  data.count <= StorageLimits.maximumRepresentationBytes,
                  data.count <= StorageLimits.maximumCaptureBytes - size else { return nil }
            if type == fileType {
                guard let value = String(data: data, encoding: .utf8),
                      let url = URL(string: value), url.isFileURL else { return nil }
            }
            return data
        }

        // 先为每个受支持 item 保存必要表示，不能让可选富文本 / 像素挤掉后续文件。
        // 文件 item 必须保留文件 URL；像素不能替代缺失或超限的文件引用。
        for (index, types) in itemTypes.enumerated() {
            let requiredTypes = types.contains(fileType) ? [fileType] : preferredTypes.filter { types.contains($0) }
            guard !requiredTypes.isEmpty else { continue }
            var represented = false
            for type in requiredTypes {
                attempted[index].insert(type)
                guard let data = try boundedData(item: index, type: type) else { continue }
                representations.append(ClipRepresentation(item: index, type: type, data: data))
                size += data.count
                represented = true
                break
            }
            // 可以舍弃同一 item 的超限表示，但不能静默丢掉整个受支持 item。
            guard represented else { throw LibraryError.unsupported }
        }

        for (index, types) in itemTypes.enumerated() {
            let allowed = types.contains(fileType) ? ClipboardFormats.rasterImages : preferredTypes
            var hasImage = representations.contains { $0.item == index && ClipboardFormats.rasterImages.contains($0.type) }
            for type in allowed where types.contains(type) && !attempted[index].contains(type) {
                guard representations.count < StorageLimits.maximumRepresentations,
                      size < StorageLimits.maximumCaptureBytes else { break }
                let isImage = ClipboardFormats.rasterImages.contains(type)
                if isImage && hasImage { continue }
                guard let data = try boundedData(item: index, type: type) else { continue }
                representations.append(ClipRepresentation(item: index, type: type, data: data))
                size += data.count
                if isImage { hasImage = true }
            }
        }
        guard !representations.isEmpty else { return nil }
        representations.sort {
            if $0.item != $1.item { return $0.item < $1.item }
            return (typeRanks[$0.type] ?? Int.max) < (typeRanks[$1.type] ?? Int.max)
        }
        var text = ""
        var files: [String] = []
        var hasImage = false
        var hasURL = false
        for index in itemTypes.indices {
            var itemText = ""
            for representation in representations where representation.item == index {
                let type = representation.type, data = representation.data
                if ClipboardFormats.rasterImages.contains(type) { hasImage = true }
                if type == stringType {
                    itemText = String(decoding: data.prefix(StorageLimits.searchableCharacters * 4), as: UTF8.self)
                }
                if type == urlType {
                    hasURL = true
                    if itemText.isEmpty { itemText = String(decoding: data.prefix(StorageLimits.searchableCharacters * 4), as: UTF8.self) }
                }
                if type == fileType, let value = String(data: data, encoding: .utf8), let url = URL(string: value) {
                    files.append(url.lastPathComponent)
                }
            }
            if !itemText.isEmpty, text.count < StorageLimits.searchableCharacters {
                if !text.isEmpty { text += "\n" }
                text += itemText.prefix(StorageLimits.searchableCharacters - text.count)
            }
        }
        if !hasURL, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
           ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil {
            hasURL = true
        }
        let kind: ClipKind = !files.isEmpty ? (ClipboardFormats.areImageFiles(files) ? .image : .file) : hasImage ? .image : hasURL ? .link : .text
        let searchable = String((!files.isEmpty ? files.joined(separator: "\n") : text).prefix(StorageLimits.searchableCharacters))
        let title: String
        if !files.isEmpty { title = files.count == 1 ? files[0] : "\(files[0]) 等 \(files.count) 个文件" }
        else if hasImage { title = "图片" }
        else { title = String(text.split(whereSeparator: \.isNewline).first ?? "富文本内容") }
        return ClipCapture(kind: kind, title: String(title.prefix(120)), excerpt: String(searchable.prefix(240)), searchText: searchable,
                           source: source, sourceBundleID: bundleID, representations: representations)
    }
}
